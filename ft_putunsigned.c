#include "ft_printf.h"

int	ft_putunsigned(unsigned int n)
{
	long	nb;
	int	count;

	nb = n;
	count = 0;
	if(nb < 0)
	{
		count += ft_putchar('-');
			nb = -nb;
	}
	if (nb >= 10)
		count += ft_putnbr(nb / 10);
	count += ft_putchar((nb % 10) + '0');
	return (count);
}
